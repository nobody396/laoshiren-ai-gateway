package rbacfixture

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	testdataDir      = "testdata"
	testdataSQLFile  = "rbac_fixture.sql"
	testdataJSONFile = "rbac_fixture.json"
	envWrite         = "RBAC_FIXTURE_WRITE"
)

// TestExportJSON 校验 JSON 导出结构正确且可回读.
// 当环境变量 RBAC_FIXTURE_WRITE=1 时, 会把生成物落盘到 testdata/rbac_fixture.json.
func TestExportJSON(t *testing.T) {
	var buf bytes.Buffer
	if err := ExportJSON(&buf); err != nil {
		t.Fatalf("ExportJSON: %v", err)
	}

	var payload fixtureExport
	if err := json.Unmarshal(buf.Bytes(), &payload); err != nil {
		t.Fatalf("unmarshal exported json: %v", err)
	}
	wantMenus := len(BaselineMenus())
	wantAPIs := len(BaselineAPIs())
	if len(payload.Menus) != wantMenus {
		t.Fatalf("menus 条数不符: got=%d want=%d", len(payload.Menus), wantMenus)
	}
	if len(payload.APIs) != wantAPIs {
		t.Fatalf("apis 条数不符: got=%d want=%d", len(payload.APIs), wantAPIs)
	}

	// 抽查几条菜单 key.
	menuKeys := make(map[string]struct{}, len(payload.Menus))
	for _, m := range payload.Menus {
		menuKeys[m.PermissionKey] = struct{}{}
	}
	for _, k := range []string{"admin:dashboard", "admin:roles", "admin:apis", "admin:menus"} {
		if _, ok := menuKeys[k]; !ok {
			t.Errorf("导出的 JSON 缺失菜单 key=%s", k)
		}
	}

	// 抽查几条 API.
	apiKeys := make(map[string]struct{}, len(payload.APIs))
	for _, a := range payload.APIs {
		apiKeys[a.Method+" "+a.Path] = struct{}{}
	}
	for _, k := range []string{"GET /admin/rbac/menu", "DELETE /admin/users/:id"} {
		if _, ok := apiKeys[k]; !ok {
			t.Errorf("导出的 JSON 缺失 API %s", k)
		}
	}

	if os.Getenv(envWrite) == "1" {
		writeTestdata(t, testdataJSONFile, buf.Bytes())
	}
}

// TestExportSQL 校验 SQL 导出 "看起来像" 合法的 psql 脚本.
func TestExportSQL(t *testing.T) {
	var buf bytes.Buffer
	if err := ExportSQL(&buf); err != nil {
		t.Fatalf("ExportSQL: %v", err)
	}

	content := buf.String()
	wantMenus := len(BaselineMenus())
	wantAPIs := len(BaselineAPIs())

	// 基本骨架断言.
	for _, want := range []string{
		"BEGIN;",
		"COMMIT;",
		"ON CONFLICT (permission_key) DO UPDATE",
		"ON CONFLICT (method, path) DO UPDATE",
		"SELECT setval('admin_menus_id_seq'",
		"SELECT setval('admin_apis_id_seq'",
		"-- Code generated by rbacfixture.ExportSQL",
	} {
		if !strings.Contains(content, want) {
			t.Errorf("SQL 缺失片段: %q", want)
		}
	}

	// INSERT 行数与 fixture 一致.
	if got := strings.Count(content, "INSERT INTO admin_menus "); got != wantMenus {
		t.Errorf("admin_menus INSERT 行数不符: got=%d want=%d", got, wantMenus)
	}
	if got := strings.Count(content, "INSERT INTO admin_apis "); got != wantAPIs {
		t.Errorf("admin_apis INSERT 行数不符: got=%d want=%d", got, wantAPIs)
	}

	// 抽查几个关键 key 的 UPSERT 存在.
	for _, k := range []string{
		"'admin:dashboard'",
		"'admin:roles'",
		"'/admin/rbac/roles/:id/menus'",
		"'/admin/accounts'",
	} {
		if !strings.Contains(content, k) {
			t.Errorf("SQL 缺失字面量 %s", k)
		}
	}

	// 单引号转义健壮性.
	if got := sqlQuote("O'Reilly"); got != "'O''Reilly'" {
		t.Errorf("sqlQuote 单引号转义错误: got=%s", got)
	}

	if os.Getenv(envWrite) == "1" {
		writeTestdata(t, testdataSQLFile, buf.Bytes())
	}
}

// writeTestdata 把字节内容落盘到 ./testdata/<name>, 不存在目录则创建.
func writeTestdata(t *testing.T, name string, data []byte) {
	t.Helper()
	if err := os.MkdirAll(testdataDir, 0o755); err != nil {
		t.Fatalf("mkdir testdata: %v", err)
	}
	full := filepath.Join(testdataDir, name)
	if err := os.WriteFile(full, data, 0o644); err != nil {
		t.Fatalf("write %s: %v", full, err)
	}
	t.Logf("已写入 %s (%d bytes)", full, len(data))
}
