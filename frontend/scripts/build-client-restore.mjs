import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const hashes = {}
for (const client of ['codex', 'claude']) {
  const outfile = `${root}public/auto-config/restore-${client}.cjs`
  await build({ absWorkingDir: root, entryPoints: [`${root}scripts/restore/${client}.cjs`], outfile, bundle: true, platform: 'node', target: 'node18', legalComments: 'inline', ...(client === 'codex' ? { banner: { js: '/* smol-toml license:\n' + readFileSync(`${root}node_modules/smol-toml/LICENSE`, 'utf8') + '\n*/' } } : {}) })
  hashes[client] = createHash('sha256').update(readFileSync(outfile)).digest('hex')
}
writeFileSync(`${root}src/generated/clientRestoreIntegrity.ts`, `// Generated by scripts/build-client-restore.mjs\nexport const clientRestoreSha256 = ${JSON.stringify(hashes, null, 2)} as const\n`)
