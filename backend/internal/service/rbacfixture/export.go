// menuExportRow 是一条菜单的可序列化快照, 与 admin_menus 表列 1:1 对齐.
// 20260505 扁平化 (migration 120): 移除 parent_id 字段.
type menuExportRow struct {
	ID            int64  `json:"id"`
	Name          string `json:"name"`
	Type          string `json:"type"`
	Path          string `json:"path"`
	Component     string `json:"component"`
	Icon          string `json:"icon"`
	PermissionKey string `json:"permission_key"`
	SortOrder     int    `json:"sort_order"`
	Status        string `json:"status"`
}

// apiExportRow 是一条 API 资源的可序列化快照, 与 admin_apis 表列 1:1 对齐.
type apiExportRow struct {
	ID          int64  `json:"id"`
	Group       string `json:"group"`
	Path        string `json:"path"`
	Method      string `json:"method"`
	Description string `json:"description"`
	SortOrder   int    `json:"sort_order"`
	Status      string `json:"status"`
}

// fixtureExport 是 ExportJSON 的顶层 schema: 菜单 + API 分开呈现.
type fixtureExport struct {
	Menus []menuExportRow `json:"menus"`
	APIs  []apiExportRow  `json:"apis"`
}

func toMenuRows(menus []*service.AdminMenu) []menuExportRow {
	out := make([]menuExportRow, 0, len(menus))
	for _, m := range menus {
		out = append(out, menuExportRow{
			ID:   m.ID,
			Name: m.Name, Type: m.Type, Path: m.Path,
			Component: m.Component, Icon: m.Icon,
			PermissionKey: m.PermissionKey,
			SortOrder:     m.SortOrder, Status: m.Status,
		})
	}
	return out
}

func toAPIRows(apis []*service.AdminAPI) []apiExportRow {
	out := make([]apiExportRow, 0, len(apis))
	for _, a := range apis {
		out = append(out, apiExportRow{
			ID: a.ID, Group: a.Group, Path: a.Path, Method: a.Method,
			Description: a.Description,
			SortOrder:   a.SortOrder, Status: a.Status,
		})
	}
	return out
}

// ExportJSON 把 [FullFixture] 写入 w, 以 UTF-8 JSON 对象形式 (menus + apis 两个字段).
//
// 用法:
//
//	f, _ := os.Create("rbac_fixture.json")
//	defer f.Close()
//	_ = rbacfixture.ExportJSON(f)
func ExportJSON(w io.Writer) error {
	menus, apis := FullFixture()
	payload := fixtureExport{
		Menus: toMenuRows(menus),
		APIs:  toAPIRows(apis),
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(payload); err != nil {
		return fmt.Errorf("encode json: %w", err)
	}
	return nil
}

// sqlQuote 将字符串安全地包成 SQL 字面量 (单引号转义), 防 SQL 注入.
func sqlQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// ExportSQL 把 menu + api fixture 写入 w, 生成一段可直接 psql 执行的幂等 SQL:
//
//   - 包裹 BEGIN / COMMIT 事务
//   - admin_menus 按 permission_key UPSERT
//   - admin_apis 按 (method, path) UPSERT
//   - 结尾重置两张表的主键序列
func ExportSQL(w io.Writer) error {
	menus, apis := FullFixture()

	bw := bufioJoiner{w: w}
	bw.writeln("-- Code generated by rbacfixture.ExportSQL; DO NOT EDIT.")
	bw.writeln("-- 来源: backend/internal/service/rbacfixture/fixture.go")
	bw.writeln(fmt.Sprintf("-- 菜单 %d 条, API %d 条", len(menus), len(apis)))
	bw.writeln("")
	bw.writeln("BEGIN;")
	bw.writeln("")

	for _, m := range menus {
		line := fmt.Sprintf(
			`INSERT INTO admin_menus `+
				`(id, name, type, path, component, icon, `+
				`permission_key, sort_order, status) VALUES `+
				`(%d, %s, %s, %s, %s, %s, %s, %d, %s) `+
				`ON CONFLICT (permission_key) DO UPDATE SET `+
				`name=EXCLUDED.name, type=EXCLUDED.type, `+
				`path=EXCLUDED.path, component=EXCLUDED.component, icon=EXCLUDED.icon, `+
				`sort_order=EXCLUDED.sort_order, status=EXCLUDED.status, updated_at=now();`,
			m.ID,
			sqlQuote(m.Name), sqlQuote(m.Type), sqlQuote(m.Path),
			sqlQuote(m.Component), sqlQuote(m.Icon),
			sqlQuote(m.PermissionKey),
			m.SortOrder, sqlQuote(m.Status),
		)
		bw.writeln(line)
	}

	bw.writeln("")

	for _, a := range apis {
		line := fmt.Sprintf(
			`INSERT INTO admin_apis `+
				`(id, "group", path, method, description, sort_order, status) VALUES `+
				`(%d, %s, %s, %s, %s, %d, %s) `+
				`ON CONFLICT (method, path) DO UPDATE SET `+
				`"group"=EXCLUDED."group", description=EXCLUDED.description, `+
				`sort_order=EXCLUDED.sort_order, status=EXCLUDED.status, updated_at=now();`,
			a.ID,
			sqlQuote(a.Group), sqlQuote(a.Path), sqlQuote(a.Method),
			sqlQuote(a.Description),
			a.SortOrder, sqlQuote(a.Status),
		)
		bw.writeln(line)
	}

	bw.writeln("")
	bw.writeln(`-- 重置主键序列, 确保后续不指定 id 的 INSERT 不会撞到 fixture.`)
	bw.writeln(`SELECT setval('admin_menus_id_seq', ` +
		`(SELECT COALESCE(MAX(id), 1) FROM admin_menus), true);`)
	bw.writeln(`SELECT setval('admin_apis_id_seq', ` +
		`(SELECT COALESCE(MAX(id), 1) FROM admin_apis), true);`)
	bw.writeln("")
	bw.writeln("COMMIT;")

	return bw.err
}

// bufioJoiner 是极简的 "Write 一堆 string 只记首个错误" 辅助.
type bufioJoiner struct {
	w   io.Writer
	err error
}

func (b *bufioJoiner) writeln(s string) {
	if b.err != nil {
		return
	}
	if _, err := io.WriteString(b.w, s); err != nil {
		b.err = err
		return
	}
	if _, err := io.WriteString(b.w, "\n"); err != nil {
		b.err = err
	}
}
