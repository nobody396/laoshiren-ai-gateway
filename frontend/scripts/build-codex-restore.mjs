import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
const outfile = `${root}public/auto-config/restore-codex.cjs`
await build({ entryPoints: [`${root}scripts/restore/codex.cjs`], outfile, bundle: true, platform: 'node', target: 'node18', legalComments: 'inline', banner: { js: '/* smol-toml license:\n' + readFileSync(`${root}node_modules/smol-toml/LICENSE`, 'utf8') + '\n*/' } })
const hash = createHash('sha256').update(readFileSync(outfile)).digest('hex')
writeFileSync(`${root}src/generated/codexRestoreIntegrity.ts`, `// Generated by scripts/build-codex-restore.mjs\nexport const codexRestoreSha256 = '${hash}'\n`)
